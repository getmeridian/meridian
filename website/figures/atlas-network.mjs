// Rebuild the engraving's stationary, language-neutral network from the same coordinates and
// depth bands as canvas: node website/figures/atlas-network.mjs [--check]. No browser or network.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { homeView, itineraries, journeys, limbFade, networkInk, roleAt, roleSize, routeBands, visibleLeg } from '../src/components/atlas-network.ts';

const file = fileURLToPath(new URL('../src/assets/network-globe.svg', import.meta.url));
const round = n => Number(n.toFixed(2));
function overlay() {
  const bands = routeBands.map(() => []);
  for (const legs of journeys) for (const leg of legs) for (const { band, xy } of visibleLeg(leg.pts, homeView)) {
    let d = '';
    for (let i = 0; i < xy.length; i += 2) d += (i ? 'L' : 'M') + round(xy[i]) + ',' + round(xy[i+1]);
    bands[band].push(d);
  }
  const lines = ['  <!-- Geographic network: generated by website/figures/atlas-network.mjs. -->',
    '  <defs><clipPath id="network-limb"><circle cx="271" cy="213" r="166.25"/></clipPath></defs>',
    '  <g clip-path="url(#network-limb)" stroke-linecap="round" stroke-linejoin="round">'];
  bands.forEach((paths, band) => {
    if (!paths.length) return;
    const d = paths.join('');
    for (const [color, width] of [[networkInk.shadow,2.3],[networkInk.line,1.1]])
      lines.push(`    <path d="${d}" stroke="${color}" stroke-opacity="${round(.66*routeBands[band])}" stroke-width="${width}"/>`);
  });
  for (const stops of itineraries) stops.forEach((city, i) => {
    const [x,y,z] = homeView(city.pos);
    if (z <= 0) return;
    const role = roleAt(i,stops.length), r = roleSize[role], dark = networkInk.shadow, gold = networkInk.marker;
    const ink = role === 'device' ? `<circle r="${r}" fill="${dark}" stroke="${gold}"/><circle r="1.15" fill="${gold}"/>` :
      role === 'relay' ? `<rect x="${-r}" y="${-r}" width="${2*r}" height="${2*r}" fill="${dark}" stroke="${gold}"/>` :
      `<path d="M0,-${r}L${r},0L0,${r}L-${r},0Z" fill="${networkInk.server}" stroke="${dark}"/>`;
    lines.push(`    <g transform="translate(${round(x)} ${round(y)})" opacity="${round(limbFade(z))}" stroke-width="1.15">${ink}</g>`);
  });
  return [...lines, '  </g>'].join('\n');
}
const source = fs.readFileSync(file, 'utf8');
const start = source.indexOf('  <!-- Geographic network:');
if (start < 0) throw new Error('Cannot locate the generated city network.');
const updated = source.slice(0,start) + overlay() + '\n</svg>\n';
if (process.argv.includes('--check')) {
  if (source !== updated) throw new Error('Globe engraving is stale. Run node website/figures/atlas-network.mjs');
} else fs.writeFileSync(file, updated);
