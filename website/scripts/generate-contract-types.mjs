import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const websiteRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(websiteRoot, "..");
const contractsRoot = path.join(repoRoot, "contracts", "meridian", "v1");
const outputRoot = path.join(websiteRoot, "src", "studio", "generated");
const header = "// Generated by website/scripts/generate-contract-types.mjs. Do not edit.\n\n";

async function readJson(relativePath) {
  return JSON.parse(await readFile(path.join(contractsRoot, relativePath), "utf8"));
}

async function readJsonl(relativePath) {
  const content = await readFile(path.join(contractsRoot, relativePath), "utf8");
  return content
    .split("\n")
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line));
}

function stableTs(value) {
  return JSON.stringify(value, null, 2);
}

async function writeManifest(outputDir, filename, exportName, value) {
  await writeFile(
    path.join(outputDir, filename),
    `${header}export const ${exportName} = ${stableTs(value)} as const;\n`,
    "utf8",
  );
}

async function copyGeneratedTypes(outputDir) {
  const schemaDir = path.join(contractsRoot, "schemas");
  const typesDir = path.join(outputDir, "schemas");
  await mkdir(typesDir, { recursive: true });

  const binName = process.platform === "win32" ? "json2ts.cmd" : "json2ts";
  const json2ts = path.join(websiteRoot, "node_modules", ".bin", binName);
  if (!existsSync(json2ts)) {
    throw new Error("Missing json2ts. Run: cd website && npm install");
  }

  execFileSync(json2ts, ["-i", schemaDir, "-o", typesDir], {
    cwd: websiteRoot,
    stdio: "inherit",
  });

  const files = (await readdir(typesDir)).filter((name) => name.endsWith(".d.ts")).sort();
  await writeFile(
    path.join(typesDir, "index.d.ts"),
    `${header}${files
      .map((file) => `export * from "./${file.replace(/\.d\.ts$/, "")}";`)
      .join("\n")}\n`,
    "utf8",
  );
}

async function generate(outputDir) {
  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });

  await copyGeneratedTypes(outputDir);
  await writeManifest(outputDir, "commands.ts", "commandCatalog", await readJson("commands.json"));
  await writeManifest(outputDir, "events.ts", "eventTypeCatalog", await readJson("events.json"));
  await writeManifest(outputDir, "workflows.ts", "workflowCatalog", await readJson("workflows/index.json"));

  const deployWorkflow = await readJson("workflows/deploy.json");
  await writeManifest(outputDir, "deployWorkflow.ts", "deployWorkflow", deployWorkflow);
  await writeManifest(
    outputDir,
    "serverOnboardingWorkflow.ts",
    "serverOnboardingWorkflow",
    await readJson("workflows/server-onboarding.json"),
  );
  await writeManifest(
    outputDir,
    "deployRequestSchema.ts",
    "deployRequestSchema",
    await readJson("schemas/deploy-request.schema.json"),
  );
  await writeManifest(
    outputDir,
    "serverConnectionDraftSchema.ts",
    "serverConnectionDraftSchema",
    await readJson("schemas/server-connection-draft.schema.json"),
  );
  await writeManifest(outputDir, "fixtures.ts", "studioFixtures", {
    deployDryRunEnvelope: await readJson("fixtures/deploy-dry-run-envelope.json"),
    deployDryRunEvents: await readJsonl("fixtures/deploy-dry-run-events.jsonl"),
    deployEvents: await readJsonl("fixtures/deploy-events.jsonl"),
    deploySuccessEnvelope: await readJson("fixtures/deploy-success-envelope.json"),
    deployUserErrorEnvelope: await readJson("fixtures/deploy-user-error-envelope.json"),
  });
  await writeFile(
    path.join(outputDir, "index.ts"),
    `${header}export * from "./commands";\nexport * from "./deployRequestSchema";\nexport * from "./deployWorkflow";\nexport * from "./events";\nexport * from "./fixtures";\nexport * from "./serverConnectionDraftSchema";\nexport * from "./serverOnboardingWorkflow";\nexport * from "./workflows";\n`,
    "utf8",
  );
}

function listFiles(root, base = root) {
  if (!existsSync(root)) {
    return [];
  }
  const entries = execFileSync("find", [root, "-type", "f"], { encoding: "utf8" })
    .split("\n")
    .filter(Boolean)
    .map((file) => path.relative(base, file))
    .sort();
  return entries;
}

function checkGenerated(tempOutput) {
  const expected = listFiles(tempOutput);
  const actual = listFiles(outputRoot);
  const errors = [];

  for (const file of expected.filter((item) => !actual.includes(item))) {
    errors.push(`missing: ${file}`);
  }
  for (const file of actual.filter((item) => !expected.includes(item))) {
    errors.push(`extra: ${file}`);
  }
  for (const file of expected.filter((item) => actual.includes(item))) {
    const wanted = readFileSync(path.join(tempOutput, file), "utf8");
    const got = readFileSync(path.join(outputRoot, file), "utf8");
    if (wanted !== got) {
      errors.push(`changed: ${file}`);
    }
  }
  return errors;
}

const check = process.argv.includes("--check");

if (check) {
  const tempRoot = mkdtempSync(path.join(tmpdir(), "meridian-contract-types-"));
  try {
    await generate(tempRoot);
    const errors = checkGenerated(tempRoot);
    if (errors.length > 0) {
      console.error("Generated Studio contract types are out of date:");
      for (const error of errors) {
        console.error(`  ${error}`);
      }
      console.error("Run: cd website && npm run contracts:generate");
      process.exitCode = 1;
    } else {
      console.log(`OK: Studio contract types current in ${outputRoot}`);
    }
  } finally {
    rmSync(tempRoot, { recursive: true, force: true });
  }
} else {
  await generate(outputRoot);
  console.log(`Wrote Studio contract types to ${outputRoot}`);
}
