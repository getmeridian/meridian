"""Regenerate ``meridian.core.geodata_lists`` from the geodata in the pinned Xray archive.

Xray refuses a whole config that names a ``geosite:``/``geoip:`` list its data
files lack, so the compiler checks routes against the names the servers really
load: node agents install both files from the same archive as the core. Needs
network (never CI); run it whenever ``XRAY_VERSION`` moves. ``--check`` compares
instead of writing.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import sys
import zipfile
from collections.abc import Iterator
from pathlib import Path

import httpx

from meridian.config import XRAY_GITHUB_URL, XRAY_SHA256, XRAY_VERSION
from meridian.core.geodata_lists import SOURCE

ASSET = "Xray-linux-64.zip"  # every Linux archive of one release carries the same geodata
SOURCE_NAME = f"Xray-core v{XRAY_VERSION} {ASSET}"
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "meridian" / "core" / "geodata_lists.py"
LINE = 100  # 8-space indent, quotes, and a trailing space stay under 120


def _varint(data: bytes, index: int) -> tuple[int, int]:
    value = shift = 0
    while True:
        byte = data[index]
        index += 1
        value |= (byte & 0x7F) << shift
        shift += 7
        if byte < 0x80:
            return value, index


def _fields(data: bytes) -> Iterator[tuple[int, bytes]]:
    """Length-delimited protobuf fields; other wire types are skipped."""
    index = 0
    while index < len(data):
        key, index = _varint(data, index)
        number, wire = key >> 3, key & 7
        if wire == 2:
            size, index = _varint(data, index)
            yield number, data[index : index + size]
            index += size
        elif wire == 0:
            _, index = _varint(data, index)
        elif wire == 5:
            index += 4
        elif wire == 1:
            index += 8
        else:
            raise ValueError(f"unsupported protobuf wire type {wire}")


def geosite_lists(data: bytes) -> set[str]:
    """``GeoSiteList`` names plus every ``name@attribute`` its domains carry."""
    names: set[str] = set()
    for number, site in _fields(data):
        if number != 1:
            continue
        code = ""
        attributes: set[str] = set()
        for field, value in _fields(site):
            if field == 1:
                code = value.decode().lower()
            elif field == 2:
                for domain_field, domain_value in _fields(value):
                    if domain_field == 3:
                        attributes |= {v.decode().lower() for f, v in _fields(domain_value) if f == 1}
        names |= {code, *(f"{code}@{attribute}" for attribute in attributes)}
    return names


def geoip_lists(data: bytes) -> set[str]:
    """``GeoIPList`` country codes and named lists (``private``, ``telegram``, ...)."""
    return {
        value.decode().lower()
        for number, entry in _fields(data)
        if number == 1
        for field, value in _fields(entry)
        if field == 1
    }


def _wrapped(names: set[str]) -> list[str]:
    lines: list[str] = []
    current = ""
    for name in sorted(names):
        candidate = f"{current} {name}".strip()
        if len(candidate) > LINE and current:
            lines.append(current)
            candidate = name
        current = candidate
    return [*lines, current] if current else lines


def render(geosite: set[str], geoip: set[str], source: str) -> str:
    def block(constant: str, names: set[str]) -> list[str]:
        body = [f'        "{line} "' for line in _wrapped(names)]
        return [f"{constant}: frozenset[str] = frozenset(", "    (", *body, "    ).split()", ")", ""]

    return (
        "\n".join(
            [
                '"""Generated by scripts/export_geodata_lists.py from the pinned Xray archive; do not edit."""',
                "",
                "from __future__ import annotations",
                "",
                f'SOURCE = "{source}"',
                "",
                *block("GEOSITE_LISTS", geosite),
                *block("GEOIP_LISTS", geoip),
            ]
        ).rstrip("\n")
        + "\n"
    )


def _archive_files() -> tuple[bytes, bytes]:
    """geosite.dat and geoip.dat from the pinned Linux archive, refused unless its sha256 matches."""
    response = httpx.get(f"{XRAY_GITHUB_URL}/v{XRAY_VERSION}/{ASSET}", follow_redirects=True, timeout=120)
    response.raise_for_status()
    if hashlib.sha256(response.content).hexdigest() != XRAY_SHA256[ASSET]:
        raise SystemExit(f"{ASSET} does not match its pinned sha256")
    with zipfile.ZipFile(io.BytesIO(response.content)) as archive:
        return archive.read("geosite.dat"), archive.read("geoip.dat")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the module is stale instead of writing it")
    args = parser.parse_args(argv)
    stale = f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/export_geodata_lists.py"
    if args.check and SOURCE != SOURCE_NAME:
        print(f"{stale} (XRAY_VERSION moved)", file=sys.stderr)
        return 1
    geosite, geoip = _archive_files()
    text = render(geosite_lists(geosite), geoip_lists(geoip), SOURCE_NAME)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(stale, file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
