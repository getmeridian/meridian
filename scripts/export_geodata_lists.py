"""Regenerate ``meridian.core.geodata_lists`` from the Xray geodata in the pinned node image.

Xray refuses a whole config that names a ``geosite:``/``geoip:`` list its data
files lack, so the compiler checks routes against the names the servers really
load. Needs Docker and network (never CI); run it whenever ``REMNAWAVE_NODE_IMAGE``
moves. ``--check`` compares instead of writing.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path

from meridian.config import REMNAWAVE_NODE_IMAGE
from meridian.core.geodata_lists import SOURCE_IMAGE

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "meridian" / "core" / "geodata_lists.py"
GEODATA_DIR = "/usr/local/share/xray"
LINE = 100  # 8-space indent, quotes, and a trailing space stay under 120


def _varint(data: bytes, index: int) -> tuple[int, int]:
    value = shift = 0
    while True:
        byte = data[index]
        index += 1
        value |= (byte & 0x7F) << shift
        shift += 7
        if byte < 0x80:
            return value, index


def _fields(data: bytes) -> Iterator[tuple[int, bytes]]:
    """Length-delimited protobuf fields; other wire types are skipped."""
    index = 0
    while index < len(data):
        key, index = _varint(data, index)
        number, wire = key >> 3, key & 7
        if wire == 2:
            size, index = _varint(data, index)
            yield number, data[index : index + size]
            index += size
        elif wire == 0:
            _, index = _varint(data, index)
        elif wire == 5:
            index += 4
        elif wire == 1:
            index += 8
        else:
            raise ValueError(f"unsupported protobuf wire type {wire}")


def geosite_lists(data: bytes) -> set[str]:
    """``GeoSiteList`` names plus every ``name@attribute`` its domains carry."""
    names: set[str] = set()
    for number, site in _fields(data):
        if number != 1:
            continue
        code = ""
        attributes: set[str] = set()
        for field, value in _fields(site):
            if field == 1:
                code = value.decode().lower()
            elif field == 2:
                for domain_field, domain_value in _fields(value):
                    if domain_field == 3:
                        attributes |= {v.decode().lower() for f, v in _fields(domain_value) if f == 1}
        names |= {code, *(f"{code}@{attribute}" for attribute in attributes)}
    return names


def geoip_lists(data: bytes) -> set[str]:
    """``GeoIPList`` country codes and named lists (``private``, ``telegram``, ...)."""
    return {
        value.decode().lower()
        for number, entry in _fields(data)
        if number == 1
        for field, value in _fields(entry)
        if field == 1
    }


def _wrapped(names: set[str]) -> list[str]:
    lines: list[str] = []
    current = ""
    for name in sorted(names):
        candidate = f"{current} {name}".strip()
        if len(candidate) > LINE and current:
            lines.append(current)
            candidate = name
        current = candidate
    return [*lines, current] if current else lines


def render(geosite: set[str], geoip: set[str], image: str) -> str:
    def block(constant: str, names: set[str]) -> list[str]:
        body = [f'        "{line} "' for line in _wrapped(names)]
        return [f"{constant}: frozenset[str] = frozenset(", "    (", *body, "    ).split()", ")", ""]

    return (
        "\n".join(
            [
                '"""Generated by scripts/export_geodata_lists.py from the pinned node image; do not edit."""',
                "",
                "from __future__ import annotations",
                "",
                f'SOURCE_IMAGE = "{image}"',
                "",
                *block("GEOSITE_LISTS", geosite),
                *block("GEOIP_LISTS", geoip),
            ]
        ).rstrip("\n")
        + "\n"
    )


def _image_files(image: str, workdir: Path) -> tuple[bytes, bytes]:
    container = subprocess.run(["docker", "create", image], check=True, capture_output=True, text=True).stdout.strip()
    try:
        for name in ("geosite.dat", "geoip.dat"):
            subprocess.run(
                ["docker", "cp", "-q", f"{container}:{GEODATA_DIR}/{name}", str(workdir / name)],
                check=True,
            )
    finally:
        subprocess.run(["docker", "rm", "-f", container], check=False, capture_output=True)
    return (workdir / "geosite.dat").read_bytes(), (workdir / "geoip.dat").read_bytes()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the module is stale instead of writing it")
    args = parser.parse_args(argv)
    stale = f"{OUTPUT.relative_to(ROOT)} is stale: run scripts/export_geodata_lists.py"
    if args.check and SOURCE_IMAGE != REMNAWAVE_NODE_IMAGE:
        print(f"{stale} (the node image moved)", file=sys.stderr)
        return 1
    subprocess.run(["docker", "pull", "-q", REMNAWAVE_NODE_IMAGE], check=True, stdout=subprocess.DEVNULL)
    with tempfile.TemporaryDirectory() as tmp:
        geosite, geoip = _image_files(REMNAWAVE_NODE_IMAGE, Path(tmp))
    text = render(geosite_lists(geosite), geoip_lists(geoip), REMNAWAVE_NODE_IMAGE)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(stale, file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
