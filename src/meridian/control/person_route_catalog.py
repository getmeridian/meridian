"""Person API declarations consumed by the authenticated admin route catalog."""

from __future__ import annotations

from meridian.control.account_schedule_models import UserSchedulePreviewRequest
from meridian.control.api_models import (
    HistoryQuery,
    UserDeleteResponse,
    UserList,
    UserReissueResponse,
)
from meridian.control.command_models import (
    CutOffPlan,
    UserCutOffRequest,
)
from meridian.control.models import (
    UserCreate,
    UserDevices,
    UserImportBatch,
    UserImportResult,
    UserPatch,
    UserRecord,
    UserUpdate,
    UserUsage,
)
from meridian.control.route_metadata import (
    CONFLICT,
    CUT_OFF_ERRORS,
    CUT_OFF_SCOPE,
    DECLARED_USER,
    HISTORY_OFF,
    NOT_FOUND,
    USER_CREDENTIALS,
)
from meridian.control.route_types import ApiRoute, ErrorResponse, route
from meridian.core.account_schedule import AccountSchedulePreview
from meridian.core.client_devices import DevicesRemoved
from meridian.core.client_limits import ClientExtendRequest
from meridian.core.clients import ClientConnections

PERSON_ROUTES: tuple[ApiRoute, ...] = (
    route(
        "GET",
        "/api/users",
        ("read", "people"),
        "list_users",
        None,
        UserList,
        "List all people and their account state.",
        credentials=True,
        description=USER_CREDENTIALS,
    ),
    route(
        "POST",
        "/api/users",
        "people",
        "create_user",
        UserCreate,
        UserRecord,
        "Create a person with their first limits.",
        credentials=True,
        refusals=(ErrorResponse(409, ("user_exists",)),),
    ),
    route(
        "POST",
        "/api/import/users",
        "admin",
        "import_users",
        UserImportBatch,
        UserImportResult,
        "Import credentials, account settings, and usage atomically.",
        credentials=False,
        refusals=(CONFLICT,),
    ),
    route(
        "POST",
        "/api/users/preview",
        "people",
        "preview_user_schedule",
        UserSchedulePreviewRequest,
        AccountSchedulePreview,
        "Preview account schedule dates without changing anything.",
        # All /api routes authenticate through _Handler._authorize(scope). This flag only marks response credentials.
        credentials=False,
        refusals=(NOT_FOUND,),
        description="Requires a people-capable API token or an authenticated owner session. Returns dates only.",
    ),
    route(
        "GET",
        "/api/users/{username}",
        ("read", "people"),
        "get_user",
        None,
        UserRecord,
        "Read one person's account state.",
        credentials=True,
        refusals=(NOT_FOUND,),
        description=USER_CREDENTIALS,
    ),
    route(
        "GET",
        "/api/users/{username}/connections",
        "people",
        "user_connections",
        None,
        ClientConnections,
        "List one person's individual connections and explicit format URLs.",
        credentials=True,
        refusals=(NOT_FOUND,),
        description="Each connection URI and format URL connects as the person.",
    ),
    route(
        "GET",
        "/api/users/{username}/usage",
        ("read", "people"),
        "user_usage",
        None,
        UserUsage,
        "Read one person's retained daily usage.",
        credentials=False,
        query_model=HistoryQuery,
        refusals=(NOT_FOUND, HISTORY_OFF),
        description="Other query options are ignored. Daily history must be enabled by the operator.",
    ),
    route(
        "PUT",
        "/api/users/{username}",
        "people",
        "put_user",
        None,
        UserRecord,
        "Ensure a person exists, preserving existing settings.",
        credentials=True,
        description="No request body is read. A missing person starts active with default limits.",
    ),
    route(
        "PATCH",
        "/api/users",
        "people",
        "patch_user",
        UserPatch,
        UserRecord,
        "Edit a person named in the request body.",
        credentials=True,
        refusals=(NOT_FOUND,),
    ),
    route(
        "PATCH",
        "/api/users/{username}",
        "people",
        "update_user",
        UserUpdate,
        UserRecord,
        "Edit only the supplied account fields.",
        credentials=True,
        refusals=(NOT_FOUND,),
    ),
    route(
        "POST",
        "/api/users/{username}/reissue",
        "people",
        "reissue_user",
        UserCutOffRequest,
        UserReissueResponse,
        "Replace a person's connection credentials.",
        credentials=True,
        body_required=False,
        body_scopes=CUT_OFF_SCOPE,
        refusals=(NOT_FOUND, CUT_OFF_ERRORS),
        description=DECLARED_USER,
    ),
    route(
        "GET",
        "/api/users/{username}/cut-off",
        "read",
        "cut_off_scope",
        None,
        CutOffPlan,
        "List inbounds affected by a session cut-off.",
        credentials=False,
        refusals=(NOT_FOUND,),
    ),
    route(
        "POST",
        "/api/users/{username}/reset-traffic",
        "people",
        "reset_user_traffic",
        None,
        UserRecord,
        "Reset a person's current-period traffic use.",
        credentials=True,
        refusals=(NOT_FOUND,),
    ),
    route(
        "POST",
        "/api/users/{username}/extend",
        "people",
        "extend_user",
        ClientExtendRequest,
        UserRecord,
        "Extend expiry from the later of now and current expiry.",
        credentials=True,
        refusals=(NOT_FOUND,),
    ),
    route(
        "GET",
        "/api/users/{username}/devices",
        ("read", "people"),
        "user_devices",
        None,
        UserDevices,
        "Read registrations allowed by the privacy level.",
        credentials=False,
        refusals=(NOT_FOUND,),
    ),
    route(
        "DELETE",
        "/api/users/{username}/devices/{device_key}",
        "people",
        "delete_user_device",
        None,
        DevicesRemoved,
        "Remove one device registration.",
        credentials=False,
        refusals=(NOT_FOUND,),
    ),
    route(
        "DELETE",
        "/api/users/{username}/devices",
        "people",
        "clear_user_devices",
        None,
        DevicesRemoved,
        "Clear all device registrations for a person.",
        credentials=False,
        refusals=(NOT_FOUND,),
    ),
    route(
        "DELETE",
        "/api/users/{username}",
        "people",
        "delete_user",
        UserCutOffRequest,
        UserDeleteResponse,
        "Remove a person and optionally queue session cut-offs.",
        credentials=False,
        body_required=False,
        body_scopes=CUT_OFF_SCOPE,
        refusals=(NOT_FOUND, CUT_OFF_ERRORS),
        description=DECLARED_USER,
    ),
)
