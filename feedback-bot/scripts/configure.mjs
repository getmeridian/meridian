import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const example = process.argv.includes('--example');
let local = {};
try {
  local = JSON.parse(await readFile(new URL('config.local.json', root), 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const number = (value, name) => {
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed === 0) {
    throw new Error(`${name} must be a non-zero safe integer`);
  }
  return parsed;
};

const sample = { inboxChatId: 123456789, adminIds: [123456789], retentionDays: 90 };
const input = example ? sample : {
  inboxChatId: process.env.FEEDBACK_INBOX_CHAT_ID ?? local.inboxChatId,
  adminIds: process.env.FEEDBACK_ADMIN_IDS?.split(',') ?? local.adminIds,
  retentionDays: process.env.FEEDBACK_RETENTION_DAYS ?? local.retentionDays ?? 90,
};
const inboxChatId = number(input.inboxChatId, 'FEEDBACK_INBOX_CHAT_ID');
if (!Array.isArray(input.adminIds) || input.adminIds.length === 0) {
  throw new Error('FEEDBACK_ADMIN_IDS must contain at least one Telegram user ID');
}
const adminIds = input.adminIds.map((id) => number(id, 'FEEDBACK_ADMIN_IDS'));
if (adminIds.some((id) => id < 0)) throw new Error('Admin IDs must be positive');
const retentionDays = Number(input.retentionDays);
if (retentionDays !== 90) {
  throw new Error('FEEDBACK_RETENTION_DAYS must be 90, matching the user-facing privacy notice');
}
if (inboxChatId > 0 && !adminIds.includes(inboxChatId)) {
  throw new Error('A personal inbox must belong to an authorized administrator');
}

await writeFile(new URL('src/lib/config.generated.ts', root),
  `// Generated by scripts/configure.mjs; do not commit.\nexport const config: { inboxChatId: number; adminIds: readonly number[]; retentionDays: number } = ${JSON.stringify({ inboxChatId, adminIds, retentionDays }, null, 2)};\n`);
// Avoid printing private destinations in CI logs.
console.log(`Feedback configuration prepared (${example ? 'example only' : 'deployment'}).`);
