"""Test generated listeners, including a live reload, without a network or production logs.

uv run python tests/systemlab/scripts/check-nginx-privacy.py LOCAL_SYSTEMLAB_EXIT_IMAGE
The image needs nginx with stream, Python and openssl; it is never pulled.
"""

from __future__ import annotations

import http.client
import shutil
import socket
import ssl
import subprocess
import sys
import tarfile
import tempfile
import time
from pathlib import Path

RUN = Path("/tmp/meridian-log-test")
FILES = ("bootstrap.conf", "bootstrap-stream.conf", "compiled.conf", "compiled-stream.conf", "acme.conf")


def render(directory: Path) -> None:
    from meridian.compiler.models import NginxArtifactPayload, NginxRouteSpec
    from meridian.provision.nginx_render import render_nginx_http_config, render_nginx_stream_config
    from meridian.reconciler.nginx_challenge import PRIVATE_CHALLENGE
    from meridian.reconciler.server_render import render_nginx_artifact

    panel = render_nginx_http_config("panel.test", 18443, "", 0, "owner", 19999, "friends")
    boot = render_nginx_stream_config("127.0.0.240", 19999, 18443, domain="panel.test")
    # Separate bootstrap and compiled stream on one test host; the fallback's own port 443 is deliberately closed.
    boot = boot.replace("listen 443;", "listen 14440;").replace("listen [::]:443;", "listen [::]:14440;")
    stream = NginxArtifactPayload(
        server_ref="test",
        layer="stream",
        listener_port=14443,
        forward_client_ip=True,
        fallback_server_name="127.0.0.241",
        fallback_strip_port=14444,
        routes=[NginxRouteSpec(match="sni", server_names=[""], backend_server_ref="test", backend_port=18543)],
    )
    http = NginxArtifactPayload(
        server_ref="test",
        layer="http",
        listener_port=18543,
        forward_client_ip=True,
        tls_hostname="panel.test",
        routes=[
            NginxRouteSpec(
                match="host_path",
                server_names=["panel.test"],
                path="/test",
                protocol="xhttp",
                backend_server_ref="test",
                backend_port=19999,
            )
        ],
    )
    for f, config in zip(
        FILES,
        (
            panel,
            boot,
            render_nginx_artifact("http", http, {}),
            render_nginx_artifact("stream", stream, {}),
            PRIVATE_CHALLENGE,
        ),
        strict=True,
    ):
        (directory / f).write_text(config)


def fetch(
    port: int, uri: str, expected: int, *, tls: bool = False, host: str = "panel.test", src: str = "127.0.0.2"
) -> None:
    if tls:
        client = http.client.HTTPSConnection(
            "127.0.0.1",
            port,
            timeout=4,
            source_address=(src, 0),
            context=ssl.create_default_context(cafile=RUN / "test-ca.pem"),
        )
    else:
        client = http.client.HTTPConnection("127.0.0.1", port, timeout=4, source_address=(src, 0))
    try:
        client.request("GET", uri, headers={"Host": host})
        response = client.getresponse()
        response.read()
        assert response.status == expected, (port, expected, response.status)
    finally:
        client.close()


def exercise(stage: str) -> None:
    fetch(80, f"/http-{stage}", 301)
    fetch(80, f"/.well-known/acme-challenge/acme-{stage}", 404, host="unlisted.test")
    fetch(14440, f"/friends/sub/tls-{stage}", 502, tls=True)
    fetch(14443, f"/test/compiled-{stage}", 502, tls=True)
    with socket.create_connection(("127.0.0.1", 14444), timeout=3, source_address=("127.0.0.2", 0)) as conn:
        conn.sendall(b"PROXY TCP4 192.0.2.42 192.0.2.15 19211 443\r\nfixture\n")
        conn.recv(10)
    fetch(18080, f"/operational-{stage}", 200, src="127.0.0.3")
    fetch(18080, f"/failed/{stage}", 502, src="127.0.0.3")
    fetch(19000, f"/tcp-operator-{stage}", 200, src="127.0.0.3")


def wait_for_operator(tcp_log: Path, count: int) -> None:
    until = time.monotonic() + 3
    while tcp_log.read_text().count("127.0.0.3|19000|") < count:
        if time.monotonic() > until:
            raise AssertionError(f"operator TCP log did not flush: {tcp_log.read_text()}")
        time.sleep(0.01)


def rpc(*args: str) -> None:
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL)


def run_inside() -> None:
    import re

    RUN.mkdir()
    for pattern in ("/etc/nginx/meridian-v4-locations", "/etc/nginx/stream.d/relay-maps"):
        Path(pattern).mkdir(parents=True, exist_ok=True)
    # The certificate path is generated by production code; all paths are inside this disposable container.
    panel = (Path("/fixture") / "bootstrap.conf").read_text()
    certdir = Path(re.search(r"ssl_certificate\s+(\S+);", panel)[1]).parent
    certdir.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "ec",
            "-pkeyopt",
            "ec_paramgen_curve:prime256v1",
            "-nodes",
            "-subj",
            "/CN=panel.test",
            "-addext",
            "subjectAltName=IP:127.0.0.1,DNS:panel.test",
            "-days",
            "1",
            "-keyout",
            str(certdir / "key.pem"),
            "-out",
            str(certdir / "fullchain.pem"),
        ],
        check=True,
        capture_output=True,
    )
    shutil.copyfile(certdir / "fullchain.pem", RUN / "test-ca.pem")
    settings = """
pid {r}/pid;
error_log {r}/error.log notice;
worker_processes 1;
events {{ worker_connections 128; }}
http {{
    access_log {r}/http.log;
    include {r}/bootstrap.conf;
    include {r}/compiled.conf;
    include {r}/acme.conf;
    server {{ listen 18080;
        location / {{return 200 'operator';}}
        location /failed/ {{proxy_pass http://127.0.0.1:19999;}}
    }}
}}
stream {{
    log_format test '$remote_addr|$server_port|$status';
    access_log {r}/tcp.log test;
    include {r}/bootstrap-stream.conf;
    include {r}/compiled-stream.conf;
    server {{ listen 19000; proxy_pass 127.0.0.1:18080; }}
}}
""".format(r=RUN)
    conf = RUN / "nginx.conf"
    conf.write_text(settings)
    for f in FILES:
        src = (Path("/fixture") / f).read_text()
        (RUN / f).write_text(re.sub(r"^\s*(?:error_log /dev/null emerg|access_log off);\s*$", "", src, flags=re.M))
    rpc("nginx", "-t", "-c", str(conf))
    rpc("nginx", "-c", str(conf))
    logs = [RUN / k for k in ("http.log", "tcp.log", "error.log")]
    try:
        exercise("before")
        wait_for_operator(logs[1], 1)
        baseline = [p.read_text() for p in logs]
        assert "acme-before" in baseline[0] and "tls-before" in baseline[2] and "compiled-before" in baseline[2]
        assert "127.0.0.2|" in baseline[1] and "14444|" in baseline[1]
        for f in FILES:
            shutil.copyfile(Path("/fixture") / f, RUN / f)
        rpc("nginx", "-t", "-c", str(conf))
        rpc("nginx", "-s", "reload", "-c", str(conf))
        until = time.monotonic() + 5
        while "gracefully shutting down" not in logs[2].read_text()[len(baseline[2]) :]:
            if time.monotonic() > until:
                raise AssertionError("nginx did not complete worker handover")
            time.sleep(0.02)
        exercise("after")
        wait_for_operator(logs[1], 2)
        fresh = [p.read_text()[len(old) :] for p, old in zip(logs, baseline, strict=True)]
        for log in fresh:
            assert not any(
                value in log
                for value in ("127.0.0.2", "192.0.2.42", "tls-after", "http-after", "acme-after", "compiled-after")
            ), "managed request or client logged"
        assert fresh[1].strip().splitlines() == ["127.0.0.3|19000|200"], (
            f"unexpected synthetic stream log: {fresh[1]!r}"
        )
        assert "operational-after" in fresh[0] and "/failed/after" in fresh[0] and "/failed/after" in fresh[2]
        print(
            "Passed: package-style inherited logs captured synthetic errors before the change; after reload "
            "the managed listeners suppressed client IPs, requests and connection errors, while the "
            "operator site and TCP listener retained their logs."
        )
    finally:
        rpc("nginx", "-s", "quit", "-c", str(conf))


if __name__ == "__main__":
    if sys.argv[1:] == ["--inside"]:
        run_inside()
    elif len(sys.argv) == 2:
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp)
            render(path)
            shutil.copyfile(__file__, path / "verify.py")
            with tempfile.TemporaryFile() as data:
                with tarfile.open(fileobj=data, mode="w") as archive:
                    for name in (*FILES, "verify.py"):
                        archive.add(path / name, arcname=name)
                data.seek(0)
                subprocess.run(
                    [
                        "docker",
                        "run",
                        "-i",
                        "--rm",
                        "--pull=never",
                        "--network",
                        "none",
                        "--entrypoint",
                        "sh",
                        sys.argv[1],
                        "-c",
                        "mkdir /fixture && tar -x -C /fixture && exec python3 /fixture/verify.py --inside",
                    ],
                    check=True,
                    stdin=data,
                )
    else:
        sys.exit(__doc__)
